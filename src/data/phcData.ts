export const INITIAL_STOCK: Record<string, Record<string, { quantity: number; daily_burn_rate: number; last_updated: string; last_updated_days_ago: number }>> = {};
phcData.stock.forEach((s) => {
  if (!INITIAL_STOCK[s.phc_id]) {
    INITIAL_STOCK[s.phc_id] = {};
  }
  const dateObj = new Date(Date.now() - s.last_updated_days_ago * 86400000);
  INITIAL_STOCK[s.phc_id][s.med_code] = {
    quantity: s.stock_units,
    daily_burn_rate: s.avg_daily_use_30d,
    last_updated: dateObj.toISOString(),
    last_updated_days_ago: s.last_updated_days_ago,
  };
});

export const INITIAL_BEDS: Record<string, { total: number; occupied: number; available: number; last_updated: string }> = {};
